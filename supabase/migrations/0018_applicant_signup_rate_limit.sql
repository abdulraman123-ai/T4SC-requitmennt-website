create table if not exists public.applicant_signup_attempts (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  created_at timestamptz not null default now()
);

create index if not exists applicant_signup_attempts_ip_created_idx
  on public.applicant_signup_attempts (ip_hash, created_at desc);

alter table public.applicant_signup_attempts enable row level security;
revoke all on table public.applicant_signup_attempts from anon, authenticated;
grant all on table public.applicant_signup_attempts to service_role;
